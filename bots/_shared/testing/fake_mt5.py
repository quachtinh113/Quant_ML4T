"""A fake ``MetaTrader5`` module for unit tests.

The real package works only on Windows with a running, logged-in terminal. Everything the
loader (and later the broker adapter) touches is reproduced here with the same names, the
same return shapes and the same conventions, so a test can pass a :class:`FakeMT5` instance
wherever the code takes an ``mt5`` module:

- ``copy_rates_range`` returns a NumPy structured array with the real field names and
  dtypes (``time`` is epoch seconds on the *server* clock read as if it were UTC);
- ``symbol_info`` returns an object with ``trade_contract_size``, ``volume_min``,
  ``volume_step``, ``volume_max``, ``digits``, ``point``, ``swap_long``, ``swap_short``,
  ``swap_rollover3days``, ``trade_mode`` and ``path``;
- ``symbol_info_tick`` returns ``time``, ``bid``, ``ask`` where ``time`` is the server clock;
- ``copy_ticks_range`` returns a ``TICKS_DTYPE`` array from ``fake.ticks[name]`` (see
  :func:`synthetic_ticks`), the shape ``bots._shared.costs_mt5`` reads;
- ``account_info().trade_mode`` is 0 for a demo account (``ACCOUNT_TRADE_MODE_DEMO``); login,
  server, equity, margin and leverage come from ``fake.account`` (a dict a test may edit);
- ``order_send`` handles ``TRADE_ACTION_DEAL`` (open, or close/reduce when the request carries
  a ``position`` ticket), ``TRADE_ACTION_PENDING`` and ``TRADE_ACTION_REMOVE``, keeps
  ``positions_get`` / ``orders_get`` consistent, validates the volume against
  ``volume_min`` / ``volume_step`` / ``volume_max`` (``TRADE_RETCODE_INVALID_VOLUME``) and can
  be scripted through ``fake.scripted_results`` (a queue of dicts: ``retcode``, ``volume``,
  ``price``, ``comment`` or ``none: True`` for a ``None`` result) to replay a partial fill, a
  requote or a rejection; every request is recorded in ``calls``;
- ``order_calc_margin`` returns ``fake.margin_per_lot[name] x volume`` (or notional /
  leverage) in the account currency, ``None`` for an unknown symbol;
- ``symbol_info_tick`` quotes ``fake.quotes[name] = (bid, ask)``;
- ``initialize`` / ``shutdown`` / ``last_error`` / ``terminal_info`` / ``symbol_select``
  / ``symbols_get`` behave like the real ones, and every call is recorded in ``calls``.

Bars are generated by :func:`synthetic_rates`: weekday server days for D1, contiguous
intraday bars for H4/H1, a deterministic random walk from a seed. Nothing here looks like
a real market; it only has to have the right shape.
"""

